# Regenerates js/regions-data.js from the iPhone app's Region.swift (boxes, places, hidden boxes).
import json, re, sys
app = sys.argv[1] if len(sys.argv) > 1 else '../sst/SeaTemp/Region.swift'
s = open(app).read()
regions = []
for m in re.finditer(r'static let (\w+) = Region\(\s*id: "(\w+)", name: "([^"]+)", shortName: "([^"]+)",\s*'
                     r'south: ([-\d.]+), north: ([-\d.]+), west: ([-\d.]+), east: ([-\d.]+),(.*?)\n    \)', s, re.S):
    _, id_, name, short, south, north, west, east, rest = m.groups()
    places = []
    for p in re.finditer(r'Place\(name: "([^"]+)", lat: ([-\d.]+), lon: ([-\d.]+)(?:, kind: \.(\w+))?(?:, side: \.(\w+))?\)', rest):
        places.append({'name': p[1], 'lat': float(p[2]), 'lon': float(p[3]), 'kind': p[4] or 'town', 'side': p[5] or 'below'})
    hidden = [dict(zip(('south', 'north', 'west', 'east'), map(float, h)))
              for h in re.findall(r'Box\(south: ([-\d.]+), north: ([-\d.]+), west: ([-\d.]+), east: ([-\d.]+)\)', rest)]
    regions.append({'id': id_, 'name': name, 'shortName': short, 'south': float(south), 'north': float(north),
                    'west': float(west), 'east': float(east), 'places': places, 'hidden': hidden})
order = re.search(r'static let all = \[([^\]]+)\]', s)[1].replace(' ', '').split(',')
var_to_id = {m[0]: m[1] for m in re.findall(r'static let (\w+) = Region\(\s*id: "(\w+)"', s)}
regions.sort(key=lambda r: [var_to_id[v] for v in order].index(r['id']))
with open('js/regions-data.js', 'w') as f:
    f.write('// Generated by tools/regions_from_app.py from the iPhone app\'s Region.swift — edit there.\n')
    f.write('export const REGION_DATA = ' + json.dumps(regions, indent=1, ensure_ascii=False) + ';\n')
print([r['id'] for r in regions], [len(r['places']) for r in regions])
